    /**
     * Get all templates with saved customizations merged over defaults.
     */
    public static function getTemplates(): array
    {
        $result = [];
        foreach (self::TEMPLATES as $key => $meta) {
            $result[$key] = self::getTemplate($key);
        }
        return $result;
    }

    /**
     * Get a single template merged with database settings.
     */
    public static function getTemplate(string $key): array
    {
        if (! isset(self::TEMPLATES[$key])) {
            throw new \InvalidArgumentException("Unknown template key: {$key}");
        }

        $meta = self::TEMPLATES[$key];
        $prefix = "email_tpl_{$key}_";

        return [
            'key'          => $key,
            'name'         => $meta['name'],
            'category'     => $meta['category'],
            'description'  => $meta['description'],
            'is_enabled'   => (bool) (Setting::get("{$prefix}is_enabled", '1') !== '0'),
            'subject'      => (string) Setting::get("{$prefix}subject", $meta['default_subject']),
            'heading'      => (string) Setting::get("{$prefix}heading", $meta['default_heading']),
            'greeting'     => (string) Setting::get("{$prefix}greeting", $meta['default_greeting']),
            'body'         => (string) Setting::get("{$prefix}body", $meta['default_body']),
            'accent_color' => (string) Setting::get("{$prefix}color", $meta['default_color']),
            'button_text'  => (string) Setting::get("{$prefix}btn_text", $meta['default_btn_text']),
            'button_url'   => (string) Setting::get("{$prefix}btn_url", $meta['default_btn_url']),
            'footer_text'  => (string) Setting::get("{$prefix}footer", $meta['default_footer']),
            'allowed_tags' => $meta['allowed_tags'],
            'admin_order_recipients' => (string) Setting::get('mail_admin_order_recipients', ''),
            'is_customized'=> self::isCustomized($key),
        ];
    }

    /**
     * Check if a template has any custom values saved in the database.
     */
    public static function isCustomized(string $key): bool
    {
        $prefix = "email_tpl_{$key}_";
        foreach (['subject', 'heading', 'greeting', 'body', 'color', 'btn_text', 'btn_url', 'footer', 'is_enabled'] as $field) {
            if (Setting::get("{$prefix}{$field}") !== null) {
                return true;
            }
        }
        return false;
    }

    /**
     * Save customized template values into settings.
     */
    public static function updateTemplate(string $key, array $data): array
    {
        if (! isset(self::TEMPLATES[$key])) {
            throw new \InvalidArgumentException("Unknown template key: {$key}");
        }

        $prefix = "email_tpl_{$key}_";

        if (array_key_exists('is_enabled', $data)) {
            $enabledVal = $data['is_enabled'] ? '1' : '0';
            Setting::put("{$prefix}is_enabled", $enabledVal);

            // Sync with corresponding notification setting key
            $settingMap = [
                'order_placed'    => 'mail_notify_customer_order_placed',
                'order_verified'  => 'mail_notify_customer_order_verified',
                'admin_new_order' => 'mail_notify_admin_new_order',
                'otp'             => 'otp_enabled',
                'password_reset'  => 'mail_notify_password_reset',
                'contact_message' => 'mail_notify_contact_message',
            ];
            if (isset($settingMap[$key])) {
                Setting::put($settingMap[$key], $enabledVal);
            }
        }
        if (array_key_exists('admin_order_recipients', $data)) {
            Setting::put('mail_admin_order_recipients', (string) $data['admin_order_recipients']);
        }
        if (array_key_exists('subject', $data)) {
            Setting::put("{$prefix}subject", (string) $data['subject']);
        }
        if (array_key_exists('heading', $data)) {
            Setting::put("{$prefix}heading", (string) $data['heading']);
        }
        if (array_key_exists('greeting', $data)) {
            Setting::put("{$prefix}greeting", (string) $data['greeting']);
        }
        if (array_key_exists('body', $data)) {
            Setting::put("{$prefix}body", (string) $data['body']);
        }
        if (array_key_exists('accent_color', $data)) {
            Setting::put("{$prefix}color", (string) $data['accent_color']);
        }
        if (array_key_exists('button_text', $data)) {
            Setting::put("{$prefix}btn_text", (string) $data['button_text']);
        }
        if (array_key_exists('button_url', $data)) {
            Setting::put("{$prefix}btn_url", (string) $data['button_url']);
        }
        if (array_key_exists('footer_text', $data)) {
            Setting::put("{$prefix}footer", (string) $data['footer_text']);
        }

        return self::getTemplate($key);
    }

    /**
     * Reset a template back to factory defaults.
     */
    public static function resetTemplate(string $key): array
    {
        if (! isset(self::TEMPLATES[$key])) {
            throw new \InvalidArgumentException("Unknown template key: {$key}");
        }

        $prefix = "email_tpl_{$key}_";
        foreach (['subject', 'heading', 'greeting', 'body', 'color', 'btn_text', 'btn_url', 'footer', 'is_enabled'] as $field) {
            \App\Models\Setting::where('key', "{$prefix}{$field}")->delete();
        }
        \App\Models\Setting::forgetCache();

        return self::getTemplate($key);
    }

    /**
     * Replace template variables in a text string.
     */
    public static function replaceTags(string $text, array $variables): string
    {
        $defaults = [
            '{site_name}'   => site_name(),
            '{contact_phone}' => (string) setting('contact_phone', '01700000000'),
            '{contact_email}' => (string) setting('contact_email', 'support@' . request()->getHost()),
            '{year}'        => date('Y'),
        ];

        $merged = array_merge($defaults, $variables);
        return str_replace(array_keys($merged), array_values($merged), $text);
    }

    /**
     * Render the subject line for a template.
     */
    public static function renderSubject(string $key, array $variables = []): string
    {
        $tpl = self::getTemplate($key);
        return self::replaceTags($tpl['subject'], $variables);
    }

